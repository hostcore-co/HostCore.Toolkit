/** Words that Go spells in capitals. */
const INITIALISMS = new Set(['id', 'url', 'og', 'tld', 'tlds', 'ttl', 'swr', 'api', 'css', 'cta', 'faq', 'html', 'json', 'vps'])

/** `domain_search` → `DomainSearch`, `location-multi-dropdown` → `LocationMultiDropdown`, `id` → `ID`. */
export function goIdentifier(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => {
      const lower = word.toLowerCase()
      if (lower === 'tlds') return 'TLDs'
      if (INITIALISMS.has(lower)) return lower.toUpperCase()
      return word[0]!.toUpperCase() + word.slice(1)
    })
    .join('')
}

/** Breaks prose into lines of at most `width` characters. */
export function wrap(text: string, width: number): string[] {
  const lines: string[] = []
  let line = ''
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line)
      line = word
    } else {
      line = line ? `${line} ${word}` : word
    }
  }
  if (line) lines.push(line)
  return lines
}

