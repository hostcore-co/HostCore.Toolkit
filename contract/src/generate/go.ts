import { resolve, type Contract, type Definition, type Field, type Schema } from '../dsl'
import { goIdentifier, wrap } from './text'

/**
 * Lines of Go source inside one declaration block. Consecutive rows with
 * the same number of cells are aligned into columns the way gofmt aligns
 * them; a comment or a single-cell row ends an alignment section.
 */
export type GoRow = { comment: string } | { cells: string[] }

export function alignRows(rows: GoRow[], indent: string): string[] {
  const out: string[] = []
  let section: string[][] = []

  const flush = (): void => {
    if (section.length === 0) return
    const columns = section[0]!.length
    const widths: number[] = []
    for (let c = 0; c < columns - 1; c++) widths.push(Math.max(...section.map((cells) => cells[c]!.length)))
    for (const cells of section) {
      out.push(indent + cells.map((cell, c) => (c < columns - 1 ? cell.padEnd(widths[c]! + 1) : cell)).join(''))
    }
    section = []
  }

  for (const row of rows) {
    if ('comment' in row) {
      flush()
      out.push(`${indent}${row.comment}`)
    } else if (row.cells.length < 2) {
      flush()
      out.push(indent + row.cells.join(''))
    } else {
      if (section.length > 0 && section[0]!.length !== row.cells.length) flush()
      section.push(row.cells)
    }
  }
  flush()
  return out
}

export function goComment(text: string, indent = ''): string[] {
  return wrap(text, 77 - indent.length).map((l) => `${indent}// ${l}`)
}

export function goString(value: string): string {
  return JSON.stringify(value)
}

export function goFileHeader(packageName: string, packageDoc?: string): string[] {
  const lines = [`// Code generated by hct contract. DO NOT EDIT.`, '']
  if (packageDoc) lines.push(...goComment(packageDoc))
  lines.push(`package ${packageName}`, '')
  return lines
}

class GoWriter {
  constructor(private readonly contract: Contract) {}

  name(def: string): string {
    return this.contract.goPrefix + def
  }

  /** Follows aliases (a definition that is only a reference) to the type they name. */
  private target(name: string): Definition {
    let def = resolve(this.contract, name)
    while (def.schema.kind === 'ref') def = resolve(this.contract, def.schema.name)
    return def
  }

  private refType(name: string): { type: string; isStruct: boolean } {
    const def = this.target(name)
    switch (def.schema.kind) {
      case 'object':
        return { type: this.name(def.name), isStruct: true }
      case 'enum':
        return { type: this.name(def.name), isStruct: false }
      case 'literal':
        return { type: 'string', isStruct: false }
      default:
        return { type: this.type(def.schema), isStruct: false }
    }
  }

  type(schema: Schema): string {
    switch (schema.kind) {
      case 'string':
      case 'literal':
      case 'enum':
      case 'page-id':
        return 'string'
      case 'number':
        return 'float64'
      case 'integer':
        return schema.bits === 64 ? 'int64' : 'int'
      case 'boolean':
        return 'bool'
      case 'array':
        return `[]${this.type(schema.items)}`
      case 'nullable':
        if (schema.inner.kind === 'array' || schema.inner.kind === 'record' || schema.inner.kind === 'json') {
          return this.type(schema.inner)
        }
        return `*${this.type(schema.inner)}`
      case 'record':
        return `map[string]${this.type(schema.values)}`
      case 'ref':
        return this.refType(schema.name).type
      case 'json':
      case 'page-data':
        return 'any'
      case 'union':
      case 'object':
        throw new Error('Go output needs unions and objects to be named definitions')
    }
  }

  private fieldType(field: Field): string {
    if (field.optional && field.schema.kind === 'ref' && this.refType(field.schema.name).isStruct) {
      return `*${this.type(field.schema)}`
    }
    return this.type(field.schema)
  }

  private struct(def: Definition): string[] {
    const schema = def.schema
    if (schema.kind !== 'object') throw new Error(`${def.name} is not an object`)
    const rows: GoRow[] = []
    let fields = Object.entries(schema.fields)
    if (schema.base) {
      const base = resolve(this.contract, schema.base).schema
      if (base.kind === 'object') fields = fields.filter(([name]) => !(name in base.fields))
      rows.push({ cells: [this.name(schema.base)] })
    }
    for (const [name, field] of fields) {
      if (field.doc) for (const line of goComment(field.doc, '\t')) rows.push({ comment: line.slice(1) })
      const tag = `\`json:"${name}${field.optional ? ',omitempty' : ''}"\``
      rows.push({ cells: [field.goName ?? goIdentifier(name), this.fieldType(field), tag] })
    }
    if (rows.length === 0) return [`type ${this.name(def.name)} struct{}`]
    return [`type ${this.name(def.name)} struct {`, ...alignRows(rows, '\t'), '}']
  }

  private enumeration(def: Definition): string[] {
    const schema = def.schema
    if (schema.kind !== 'enum') throw new Error(`${def.name} is not an enum`)
    const type = this.name(def.name)
    const rows: GoRow[] = schema.values.map((v) => ({ cells: [`${type}${goIdentifier(v)}`, type, `= ${goString(v)}`] }))
    const out = [`type ${type} string`, '', 'const (', ...alignRows(rows, '\t'), ')']
    if (schema.open) {
      out.push('')
      out.push(
        ...goComment(
          `${type}Fallback is what a contract that does not know a ${type} value receives in its place.`,
        ),
      )
      out.push(`const ${type}Fallback = ${type}${goIdentifier(schema.open.fallback)}`)
    }
    return out
  }

  definition(def: Definition): string[] | null {
    switch (def.schema.kind) {
      case 'object':
        return [...goComment(`${this.name(def.name)} ${def.doc}`), ...this.struct(def)]
      case 'enum':
        return [...goComment(`${this.name(def.name)} ${def.doc}`), ...this.enumeration(def)]
      default:
        // Literals, aliases and unions have no Go type of their own: fields
        // that use them take the underlying type.
        return null
    }
  }
}

/** Renders a contract as Go structs in the given package. */
export function generateGoContract(contract: Contract, packageName: string): string {
  const writer = new GoWriter(contract)
  const lines = goFileHeader(packageName)
  lines.push(...goComment(`${contract.goPrefix}Contract is the version string of contract "${contract.version}".`))
  lines.push(`const ${contract.goPrefix}Contract = ${goString(contract.version)}`, '')
  for (const def of contract.definitions) {
    const out = writer.definition(def)
    if (out) lines.push(...out, '')
  }
  return lines.join('\n').replace(/\n+$/, '\n')
}

