import { afterAll, describe, expect, it } from 'bun:test'
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { Definitions, t, type Contract } from '../src/dsl'
import { generateAll } from '../src/generate'
import { alignRows, generateGoContract } from '../src/generate/go'
import { generateJsonSchema } from '../src/generate/json-schema'
import { EMBEDDED_MODULES, embeddedSource } from '../src/generate/ts-registry'
import { generateTypeScript } from '../src/generate/typescript'
import { goIdentifier } from '../src/generate/text'

const contractDir = join(import.meta.dir, '..')
const toolkitDir = join(contractDir, '..')
const scratch = mkdtempSync(join(tmpdir(), 'hct-contract-'))

afterAll(() => rmSync(scratch, { recursive: true, force: true }))

function sample(): Contract {
  const d = new Definitions()
  d.define('Kind', 'is a kind.', t.openEnum(['a', 'b-c'], 'a'))
  d.define(
    'Thing',
    'is a thing.',
    t.object({
      id: t.string(),
      kind: t.ref('Kind'),
      count: t.doc('How many.', t.integer({ bits: 64 })),
      parent: t.optional(t.ref('Thing')),
      tags: t.nullable(t.array(t.string())),
    }),
  )
  d.extend('Special', 'is a special thing.', 'Thing', { extra: t.boolean() })
  return { version: '9', goPrefix: 'V9', definitions: d.list, pages: { home: 'Thing' } }
}

describe('generators', () => {
  it('write Go in the shape gofmt produces', () => {
    expect(generateGoContract(sample(), 'demo')).toBe(
      [
        '// Code generated by hct contract. DO NOT EDIT.',
        '',
        'package demo',
        '',
        '// V9Contract is the version string of contract "9".',
        'const V9Contract = "9"',
        '',
        '// V9Kind is a kind.',
        'type V9Kind string',
        '',
        'const (',
        '\tV9KindA  V9Kind = "a"',
        '\tV9KindBC V9Kind = "b-c"',
        ')',
        '',
        '// V9KindFallback is what a contract that does not know a V9Kind value receives',
        '// in its place.',
        'const V9KindFallback = V9KindA',
        '',
        '// V9Thing is a thing.',
        'type V9Thing struct {',
        '\tID   string `json:"id"`',
        '\tKind V9Kind `json:"kind"`',
        '\t// How many.',
        '\tCount  int64    `json:"count"`',
        '\tParent *V9Thing `json:"parent,omitempty"`',
        '\tTags   []string `json:"tags"`',
        '}',
        '',
        '// V9Special is a special thing.',
        'type V9Special struct {',
        '\tV9Thing',
        '\tExtra bool `json:"extra"`',
        '}',
        '',
      ].join('\n'),
    )
  })

  it('write TypeScript with extends, optional keys and open enums', () => {
    const ts = generateTypeScript(sample(), 'A sample.')
    expect(ts).toContain("export type Kind = 'a' | 'b-c' | (string & {})")
    expect(ts).toContain("export const KindFallback = 'a'")
    expect(ts).toContain('export interface Thing {\n  id: string\n  kind: Kind\n  /** How many. */\n  count: number\n  parent?: Thing\n  tags: string[] | null\n}')
    expect(ts).toContain('export interface Special extends Thing {\n  extra: boolean\n}')
  })

  it('write JSON Schema with required keys and nullable values', () => {
    const schema = generateJsonSchema(sample()) as any
    expect(schema.oneOf).toEqual([{ $ref: '#/$defs/Thing' }])
    expect(schema.$defs.Thing.required).toEqual(['id', 'kind', 'count', 'tags'])
    expect(schema.$defs.Thing.properties.tags).toEqual({ anyOf: [{ type: 'array', items: { type: 'string' } }, { type: 'null' }] })
    expect(schema.$defs.Kind['x-open-enum']).toEqual({ known: ['a', 'b-c'], fallback: 'a' })
    expect(schema.$defs.Special.properties.extra).toEqual({ type: 'boolean' })
  })

  it('align rows the way gofmt does', () => {
    expect(
      alignRows(
        [{ cells: ['A', 'int', '`a`'] }, { cells: ['Bbb', 'string', '`b`'] }, { comment: '// x' }, { cells: ['C', 'bool', '`c`'] }],
        '\t',
      ),
    ).toEqual(['\tA   int    `a`', '\tBbb string `b`', '\t// x', '\tC bool `c`'])
  })

  it('spell Go initialisms', () => {
    expect(goIdentifier('og_image')).toBe('OGImage')
    expect(goIdentifier('tlds')).toBe('TLDs')
    expect(goIdentifier('location-multi-dropdown')).toBe('LocationMultiDropdown')
    expect(goIdentifier('checkout_url')).toBe('CheckoutURL')
  })

  it('embed only modules without imports', () => {
    for (const file of EMBEDDED_MODULES) expect(embeddedSource(file)).not.toMatch(/^\s*import\s/m)
  })

  it('match the committed dist and contract 1 fixtures', () => {
    const files = generateAll(contractDir)
    for (const [path, content] of Object.entries(files)) {
      expect({ path, content: readFileSync(join(contractDir, path), 'utf8') }).toEqual({ path, content })
    }
  })

  it('keep the generated TypeScript self-contained', () => {
    for (const file of ['contract-1.ts', 'contract-2026-11.ts', 'registry.ts']) {
      expect(readFileSync(join(contractDir, 'dist', 'ts', file), 'utf8')).not.toMatch(/^\s*import\s/m)
    }
  })
})

const gofmt = Bun.which('gofmt')

describe.skipIf(!gofmt)('generated Go', () => {
  it('is gofmt-clean', () => {
    const prefixes = join(scratch, 'prefixes.go')
    const run = Bun.spawnSync(
      ['bun', join(toolkitDir, 'cli', 'index.ts'), 'contract', 'generate-go', '--kind', 'frontend-prefixes', '--package', 'routes', '--out', prefixes],
    )
    expect(run.exitCode).toBe(0)
    const demo = join(scratch, 'demo.go')
    writeFileSync(demo, generateGoContract(sample(), 'demo'))
    const check = Bun.spawnSync([gofmt!, '-l', join(contractDir, 'dist', 'go', 'contract'), prefixes, demo])
    expect(check.exitCode).toBe(0)
    expect(check.stdout.toString()).toBe('')
  })
})

describe('hct contract', () => {
  const hct = (...args: string[]) => Bun.spawnSync(['bun', join(toolkitDir, 'cli', 'index.ts'), 'contract', ...args])

  it('check passes on a fresh copy and fails once dist is edited', () => {
    const copy = join(scratch, 'contract')
    cpSync(contractDir, copy, { recursive: true, filter: (src) => !src.includes('__tests__') })

    expect(hct('check', '--contract-dir', copy).exitCode).toBe(0)

    const target = join(copy, 'dist', 'go', 'contract', 'registry.go')
    writeFileSync(target, `${readFileSync(target, 'utf8')}\n// edited\n`)
    writeFileSync(join(copy, 'dist', 'ts', 'stray.ts'), 'export {}\n')
    const stale = hct('check', '--contract-dir', copy)
    expect(stale.exitCode).toBe(1)
    expect(stale.stderr.toString()).toContain('dist/go/contract/registry.go (out of date)')
    expect(stale.stderr.toString()).toContain('dist/ts/stray.ts (not generated by anything)')

    expect(hct('generate', '--contract-dir', copy).exitCode).toBe(0)
    rmSync(join(copy, 'dist', 'ts', 'stray.ts'))
    expect(hct('check', '--contract-dir', copy).exitCode).toBe(0)
  })

  it('check fails when a source fixture changes without regenerating', () => {
    const copy = join(scratch, 'contract-fixture')
    cpSync(contractDir, copy, { recursive: true, filter: (src) => !src.includes('__tests__') })
    const source = join(copy, 'fixtures', '2026-11', 'home.json')
    writeFileSync(source, readFileSync(source, 'utf8').replace('"Acme Hosting"', '"Acme Hosting Ltd"'))
    const stale = hct('check', '--contract-dir', copy)
    expect(stale.exitCode).toBe(1)
    expect(stale.stderr.toString()).toContain('fixtures/1/home.json (out of date)')
  })

  it('generate-go writes the contract package under another name', () => {
    const out = join(scratch, 'go-out')
    expect(hct('generate-go', '--kind', 'contract', '--package', 'storefront', '--out', out).exitCode).toBe(0)
    expect(readFileSync(join(out, 'registry.go'), 'utf8')).toContain('package storefront\n')
    expect(readFileSync(join(out, 'v202611.go'), 'utf8')).toContain('type V202611PageEnvelope struct')
  })

  it('generate-go writes the frontend prefixes', () => {
    const out = join(scratch, 'registry_gen.go')
    expect(hct('generate-go', '--kind', 'frontend-prefixes', '--package', 'routes', '--out', out).exitCode).toBe(0)
    const text = readFileSync(out, 'utf8')
    expect(text).toContain('package routes\n')
    expect(text).toContain('var FrontendPrefixes = []string{\n\t"/checkout",')
    expect(text).not.toContain('"/domains"')
  })

  it('generate-go refuses a bad package name or kind', () => {
    expect(hct('generate-go', '--kind', 'frontend-prefixes', '--package', 'Bad-Name', '--out', join(scratch, 'x.go')).exitCode).toBe(1)
    expect(hct('generate-go', '--kind', 'other', '--package', 'p', '--out', join(scratch, 'x.go')).exitCode).toBe(1)
  })
})
